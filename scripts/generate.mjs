import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const projectRoot = fileURLToPath(new URL('../', import.meta.url));
export const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const relativeKey = (from, to) => relative(from, to).split(sep).join('/');

export function readProject(root = projectRoot) {
  return validateProject(JSON.parse(readFileSync(join(root, 'project.json'), 'utf8')));
}

export function validateProject(project) {
  for (const key of ['name', 'version', 'title', 'description', 'endpoint', 'registryName']) {
    if (typeof project[key] !== 'string' || !project[key].trim()) throw new Error(`project.${key} is required`);
  }
  if (!/^[a-z0-9-]+$/.test(project.name)) throw new Error('project.name must be kebab-case');
  if (!/^\d+\.\d+\.\d+(?:-[a-zA-Z0-9.-]+)?$/.test(project.version)) throw new Error('project.version must be semantic versioning');
  const endpoint = new URL(project.endpoint);
  if (endpoint.protocol !== 'https:' || endpoint.username || endpoint.password) throw new Error('project.endpoint must be anonymous HTTPS');
  if (!/^[a-z0-9.-]+\/[a-z0-9-]+$/.test(project.registryName)) throw new Error('project.registryName must have a namespace/name');
  if (project.repository !== null) validateRepository(project.repository);
  if (!Array.isArray(project.maintainers) || project.maintainers.some((name) => typeof name !== 'string' || name.length > 39 || !/^[a-zA-Z0-9]+(?:-[a-zA-Z0-9]+)*$/.test(name))) {
    throw new Error('project.maintainers must contain real GitHub usernames, or remain empty');
  }
  if (new Set(project.maintainers).size !== project.maintainers.length) throw new Error('project.maintainers must be unique');
  if (typeof project.license !== 'string' || !project.license) throw new Error('project.license must contain the owner-approved license identifier');
  if (project.securityContact !== null && (typeof project.securityContact !== 'string' || !project.securityContact.trim())) throw new Error('project.securityContact must be null or a supplied private-reporting contact');
  return project;
}

export function validateRepository(value) {
  const url = new URL(value);
  if (url.protocol !== 'https:' || url.username || url.password || url.search || url.hash || url.pathname === '/') {
    throw new Error('Repository must be a public HTTPS repository URL without credentials, query, or fragment');
  }
  return url;
}

function filesUnder(directory) {
  return readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name, 'en')).flatMap((entry) => {
    const path = join(directory, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`Skill files must be regular files, not symlinks: ${path}`);
    return entry.isDirectory() ? filesUnder(path) : [path];
  });
}

export function verifyProvenance(root = projectRoot) {
  const provenance = JSON.parse(readFileSync(join(root, 'schemas/provenance.json'), 'utf8'));
  if (provenance.snapshot !== 'schemas/tools.json') throw new Error('Schema provenance must identify schemas/tools.json');
  const bytes = readFileSync(join(root, provenance.snapshot));
  if (createHash('sha256').update(bytes).digest('hex') !== provenance.sha256) throw new Error('Public schema SHA256 mismatch; review the export and update provenance deliberately');
  const tools = JSON.parse(bytes.toString('utf8'));
  if (!Array.isArray(tools) || tools.map((tool) => tool.name).join(',') !== 'search_plans,compare_trip_options') throw new Error('Unexpected public tool names');
  for (const tool of tools) {
    if (tool.inputSchema.type !== 'object' || tool.inputSchema.additionalProperties !== false || tool.annotations.readOnlyHint !== true || tool.annotations.destructiveHint !== false) throw new Error(`Invalid public tool contract: ${tool.name}`);
  }
  return bytes;
}

export function generatedFiles(root = projectRoot) {
  const p = readProject(root);
  verifyProvenance(root);
  const outputs = new Map();
  const emit = (path, value) => outputs.set(path, typeof value === 'string' ? value : json(value));
  const http = { type: 'http', url: p.endpoint };
  const claude = { mcpServers: { esimx: http } };
  emit('.mcp.json', claude);
  emit('configs/claude-code.json', claude);
  emit('configs/codex.toml', `# Generated by scripts/generate.mjs.\n[mcp_servers.esimx]\nurl = ${JSON.stringify(p.endpoint)}\n`);
  emit('configs/cursor.json', { mcpServers: { esimx: { url: p.endpoint } } });
  emit('configs/gemini-cli.json', { mcpServers: { esimx: { httpUrl: p.endpoint } } });
  emit('configs/vscode.json', { servers: { esimx: http } });
  emit('gemini-extension.json', {
    name: p.name,
    version: p.version,
    description: p.description,
    mcpServers: { esimx: { httpUrl: p.endpoint } },
    contextFileName: 'GEMINI.md',
  });
  emit('GEMINI.md', `# eSIMX travel planning\n\nFor eSIM plan searches and multi-country comparisons, read [the travel skill](skills/esimx-travel/SKILL.md). The extension connects to the anonymous, read-only eSIMX catalog at ${p.endpoint}. Use the discovered tools; this extension supplies no purchase or account actions.\n`);
  const identity = 'eSIMX';
  const plugin = {
    name: 'esimx',
    version: p.version,
    description: p.description,
    author: { name: identity },
    ...(p.repository ? { repository: p.repository } : {}),
    license: p.license,
    keywords: ['esim', 'travel', 'mcp'],
  };
  emit('plugins/esimx/.claude-plugin/plugin.json', plugin);
  emit('plugins/esimx/.mcp.json', claude);
  emit('.claude-plugin/marketplace.json', {
    name: 'esimx-local',
    description: 'eSIMX travel-planning plugin marketplace.',
    version: p.version,
    owner: { name: identity },
    plugins: [{ name: 'esimx', source: './plugins/esimx' }],
  });
  emit('plugins/esimx/README.md', `# eSIMX plugin\n\n## Purpose\n\nConnect Claude Code to the anonymous, read-only eSIMX catalog and load the [travel skill](skills/esimx-travel/SKILL.md). No local server, API key, or account is required.\n\n## Local setup\n\n1. Use a current Claude Code installation with plugin and Streamable HTTP support.\n2. From the repository root, start \`claude --plugin-dir ./plugins/esimx\`. This loads the plugin for that session without publishing it.\n3. Inspect the MCP connection, then request an eSIM search or trip comparison. Expect the \`search_plans\` and \`compare_trip_options\` tools.\n\nIf the connection fails, check outbound HTTPS access to ${p.endpoint}. On HTTP 429, wait for \`Retry-After\`; on HTTP 403, report the client restriction without bypassing it.\n\n## Distribution status\n\n${p.repository ? `Repository: ${p.repository}.` : 'Remote repository URL is pending.'} The plugin author and marketplace owner use the eSIMX product brand. Repository material is licensed under ${p.license}. Directory submissions need separate approval; Registry submission also needs domain ownership proof.\n\nThe skill references are bundled inside this plugin. Install either this plugin or a standalone connection as appropriate; avoid duplicate eSIMX connections.\n`);
  const source = p.repository ? validateRepository(p.repository).hostname : null;
  emit('server.json', {
    $schema: 'https://static.modelcontextprotocol.io/schemas/2025-12-11/server.schema.json',
    name: p.registryName,
    description: p.description,
    title: p.title,
    version: p.version,
    ...(p.repository ? { repository: { url: p.repository, source: source === 'github.com' ? 'github' : source === 'gitlab.com' ? 'gitlab' : source } } : {}),
    remotes: [{ type: 'streamable-http', url: p.endpoint }],
  });
  emit('configs/glama.template.json', { $schema: 'https://glama.ai/mcp/schemas/server.json', maintainers: [] });
  if (p.repository && source === 'github.com' && p.maintainers.length) {
    emit('glama.json', { $schema: 'https://glama.ai/mcp/schemas/server.json', maintainers: p.maintainers });
  }
  const canonical = join(root, 'skills/esimx-travel');
  const schema = readFileSync(join(root, 'schemas/tools.json'), 'utf8');
  emit('skills/esimx-travel/references/tools.json', schema);
  for (const destination of ['plugins/esimx/skills/esimx-travel', '.agents/skills/esimx-travel']) {
    for (const path of filesUnder(canonical)) {
      if (relativeKey(canonical, path) === 'references/tools.json') continue;
      emit(`${destination}/${relativeKey(canonical, path)}`, readFileSync(path, 'utf8'));
    }
    emit(`${destination}/references/tools.json`, schema);
  }
  return outputs;
}

export function generate({ root = projectRoot, check = false } = {}) {
  const outputs = generatedFiles(root);
  const drift = [];
  for (const [path, content] of outputs) {
    const destination = join(root, path);
    if (existsSync(destination) && readFileSync(destination, 'utf8') === content) continue;
    drift.push(path);
    if (!check) {
      mkdirSync(dirname(destination), { recursive: true });
      writeFileSync(destination, content);
    }
  }
  // These directories belong entirely to generation. Removed canonical references
  // must also disappear from installed copies, rather than silently surviving.
  const stale = ['glama.json'];
  for (const directory of ['plugins/esimx/skills/esimx-travel', '.agents/skills/esimx-travel']) {
    if (existsSync(join(root, directory))) stale.push(...filesUnder(join(root, directory)).map((path) => relativeKey(root, path)));
  }
  for (const path of new Set(stale)) {
    if (outputs.has(path) || !existsSync(join(root, path))) continue;
    drift.push(path);
    if (!check) rmSync(join(root, path));
  }
  return { drift, count: outputs.size };
}

if (process.argv[1] && import.meta.url === pathToFileURL(realpathSync(resolve(process.argv[1]))).href) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== '--check')) throw new Error('Usage: node scripts/generate.mjs [--check]');
  const check = args.includes('--check');
  const result = generate({ check });
  if (check && result.drift.length) {
    console.error(`Generated file drift:\n${result.drift.map((path) => `  ${path}`).join('\n')}\nRun npm run generate.`);
    process.exitCode = 1;
  } else {
    console.log(`${check ? 'Checked' : 'Generated'} ${result.count} files${check ? '; no drift' : `; ${result.drift.length} updated`}.`);
  }
}
